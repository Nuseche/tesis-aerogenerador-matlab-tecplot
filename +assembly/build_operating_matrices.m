function ops = build_operating_matrices(model,reduced,state,cfg)
%BUILD_OPERATING_MATRICES Form full and constraint-reduced operating system.
%   Inertial snapshot: D=C+G+massRate. Coordinate-transport stiffness and
%   time-dependent root constraints are kept as separate named components.
    if nargin<3||isempty(state),state=struct();end
    if nargin<4,cfg=struct();end
    Tc=sparse(reduced.Tc);
    if isfield(reduced,"full")&&isfield(reduced.full,"M"),M=sparse(reduced.full.M);else,error("assembly:build_operating_matrices:MissingFullMass","reduced.full.M is required.");end
    if isfield(reduced.full,"Ke"),Ke=sparse(reduced.full.Ke);else,error("assembly:build_operating_matrices:MissingFullStiffness","reduced.full.Ke is required.");end
    [Kaero,Caero,aeroReport]=assembly.linearize_aerodynamic_loads( ...
        model,state,cfg,size(Ke,1));
    embeddedAero=sparse(size(Ke,1),size(Ke,2));
    aerodynamicIncludedInEquilibrium=false;
    if isfield(state,'aerodynamicStiffnessFull')&& ...
            ~isempty(state.aerodynamicStiffnessFull)
        embeddedAero=sparse(state.aerodynamicStiffnessFull);
        if ~isequal(size(embeddedAero),size(Ke))|| ...
                any(~isfinite(nonzeros(embeddedAero)))
            error('assembly:build_operating_matrices:InvalidEmbeddedAero', ...
                'The aerodynamic equilibrium tangent is invalid.');
        end
        if isfield(state,'loadParts')&&isfield(state.loadParts,'aerodynamicDetails')
            aerodynamicIncludedInEquilibrium= ...
                logical(state.loadParts.aerodynamicDetails.active);
        end
    end
    if isfield(state,'tangentFull')&&~isempty(state.tangentFull)
        equilibriumTangent=sparse(state.tangentFull);
        if ~isequal(size(equilibriumTangent),size(Ke))|| ...
                any(~isfinite(nonzeros(equilibriumTangent)))
            error('assembly:build_operating_matrices:InvalidEquilibriumTangent', ...
                'state.tangentFull must be a finite full-system matrix.');
        end
        % The equilibrium tangent contains +Kaero whenever the same load
        % function participated in Newton. Keep it out of Kg so Kaero is
        % added exactly once below as a named dynamic component.
        Kg=equilibriumTangent-Ke-embeddedAero;
        KOmega=sparse(size(Ke,1),size(Ke,2));
        if isfield(state,'elementAxialForces'),axial=state.elementAxialForces;
        else,axial=zeros(numel(model.mesh.elements.id),1);end
        if isfield(state,'elementCentrifugalAxialForces')
            centrifugalAxial=state.elementCentrifugalAxialForces;
        else,centrifugalAxial=zeros(size(axial));end
        alreadyIncluded=true;
        if isfield(state,'stiffnessSourceLedger')
            sourceLedger=state.stiffnessSourceLedger;
        else
            sourceLedger=struct('elastic',"Ke",'internalGeometric', ...
                "state.tangentFull-Ke",'centrifugal', ...
                "already embedded in state tangent", ...
                'operatingStorage',"combined once in Kg; KOmega=0");
        end
    else
        [Kg,axial]=assembly.assemble_geometric_stiffness(model,state,cfg);
        alreadyIncluded=logicalField(state,"centrifugalIncludedInKg",false)|| ...
            logicalField(state,"centrifugalAlreadyInKg",false);
        if alreadyIncluded
            KOmega=sparse(size(Ke,1),size(Ke,2));
            centrifugalAxial=zeros(size(axial));
        else
            [KOmega,centrifugalAxial]= ...
                assembly.assemble_centrifugal_stiffness(model,state,cfg);
        end
        sourceLedger=struct('elastic',"Ke",'internalGeometric', ...
            "legacy recovered axial-force Kg",'centrifugal', ...
            string(choose(alreadyIncluded,"included in Kg","separate KOmega")), ...
            'operatingStorage',"legacy fallback");
    end
    [G,gyroReport]=assembly.assemble_gyroscopic_matrix(model,state,cfg);
    dampingState=state;dampingState.Caero=Caero;
    [C,dampingParts]=assembly.assemble_damping_matrix( ...
        model,M,Ke,dampingState,cfg);
    [f,loadParts]=assembly.assemble_load_vector(model,cfg,state);

    massRate=gyroReport.massRate;Ktransport=gyroReport.Ktransport;
    K=Ke+Kg+KOmega+Kaero+Ktransport;D=C+G+massRate;
    ops=struct();
    ops.full=struct("M",M,"C",C,"G",G,"D",D,"Ke",Ke,"Kg",Kg, ...
        "KOmega",KOmega,"Kaero",Kaero,"K",K,"f",f, ...
        "massRate",massRate,"Ktransport",Ktransport, ...
        "Cstruct",dampingParts.structural,"Cfoundation",dampingParts.foundation, ...
        "Caero",dampingParts.aerodynamic,"Cdrivetrain",dampingParts.drivetrain);
    if isfield(reduced,"free"),free=double(reduced.free(:));else,free=(1:size(Tc,2)).';end
    Tanalysis=Tc(:,free);
    bodies=struct();if isfield(model,'rigidBodies'),bodies=model.rigidBodies;end
    constraintMotion=rigid.rotating_constraint_derivatives( ...
        model,bodies,0,gyroReport.omega);
    if norm(constraintMotion.T-Tc,'fro')>1e-12*max(norm(Tc,'fro'),1)
        error('assembly:build_operating_matrices:ConstraintFrameMismatch', ...
            'Dynamic constraint map must equal the reference equilibrium map.');
    end
    Td=constraintMotion.Tdot(:,free);Tdd=constraintMotion.Tddot(:,free);
    constraintD=2*Tanalysis.'*M*Td;
    constraintK=Tanalysis.'*(D*Td+M*Tdd);
    reducedMassRate=Tanalysis.'*massRate*Tanalysis+ ...
        Td.'*M*Tanalysis+Tanalysis.'*M*Td;
    reducedGyro=Tanalysis.'*G*Tanalysis+ ...
        Tanalysis.'*M*Td-Td.'*M*Tanalysis;
    ops.reduced=struct("M",Tanalysis.'*M*Tanalysis,"C",Tanalysis.'*C*Tanalysis, ...
        "G",reducedGyro,"D",Tanalysis.'*D*Tanalysis+constraintD, ...
        "massRate",reducedMassRate,"constraintD",constraintD, ...
        "Ktransport",Tanalysis.'*Ktransport*Tanalysis, ...
        "constraintK",constraintK,"Tdot",Td,"Tddot",Tdd, ...
        "Cstruct",Tanalysis.'*dampingParts.structural*Tanalysis, ...
        "Cfoundation",Tanalysis.'*dampingParts.foundation*Tanalysis, ...
        "Caero",Tanalysis.'*dampingParts.aerodynamic*Tanalysis, ...
        "Cdrivetrain",Tanalysis.'*dampingParts.drivetrain*Tanalysis, ...
        "Ke",Tanalysis.'*Ke*Tanalysis,"Kg",Tanalysis.'*Kg*Tanalysis, ...
        "KOmega",Tanalysis.'*KOmega*Tanalysis,"Kaero",Tanalysis.'*Kaero*Tanalysis, ...
        "K",Tanalysis.'*K*Tanalysis+constraintK,"f",Tanalysis.'*f,"Tc",Tanalysis, ...
        "constraintTc",Tc,"freeConstraintDofs",free,"fixed",zeros(0,1), ...
        "free",(1:numel(free)).');
    ops.diagnostics=struct("axialForces",axial,"centrifugalAxialForces",centrifugalAxial, ...
        "centrifugalIncludedInKg",alreadyIncluded,"gyroscopic",gyroReport, ...
        "stiffnessSourceLedger",sourceLedger,"damping",dampingParts, ...
        "aerodynamics",aeroReport,"loads",loadParts, ...
        "aerodynamicIncludedInEquilibrium",aerodynamicIncludedInEquilibrium, ...
        "aerodynamicTangentConsistencyError", ...
        norm(embeddedAero-Kaero,'fro')/max(norm(Kaero,'fro'),1));
    ops.diagnostics.coordinateFrame="inertial_snapshot_at_reference_geometry";
    ops.diagnostics.constraintMotion=constraintMotion;
    ops.diagnostics.massRateIdentityError= ...
        norm(ops.reduced.D-ops.reduced.C-ops.reduced.G-reducedMassRate,'fro')/ ...
        max(norm(ops.reduced.D,'fro'),1);
    ops.diagnostics.linearizationScope= ...
        "reference-configuration inertia, quadratic spin potential, prestressed elastic tangent; frozen azimuth";
end
function tf=logicalField(s,name,defaultValue)
    if isfield(s,name),tf=logical(s.(name));else,tf=defaultValue;end
end
function value=choose(condition,a,b)
    if condition,value=a;else,value=b;end
end
