function evidence=extract_journal_operating_evidence(projectRoot,outputFile)
%EXTRACT_JOURNAL_OPERATING_EVIDENCE Extract persisted scientific evidence.
%   Reads named variables from successful MAT snapshots. No model assembly,
%   equilibrium solution, eigensolution, or time integration is performed.
%   Only the requested derived JSON is written; original runs are untouched.
if nargin<1||isempty(projectRoot)
    projectRoot=fileparts(fileparts(mfilename('fullpath')));
end
if nargin<2||isempty(outputFile)
    outputFile=fullfile(projectRoot,'docs','manuscrito_integrado_20260919', ...
        'evidence','operating_results.json');
end
modalRelative='runs/run_20260919_182410_438_gyro_energy_corrected_20260919';
seismicRelative='runs/run_20260919_183052_480_gyro_corrected_seismic_20260919';
modalFolder=fullfile(projectRoot,modalRelative);
seismicFolder=fullfile(projectRoot,seismicRelative);
assert(isfile(fullfile(modalFolder,'SUCCESS'))&& ...
    isfile(fullfile(seismicFolder,'SUCCESS')),'journal:UnsuccessfulRun', ...
    'Both corrected runs must have their persisted SUCCESS marker.');
model=readVariable(modalFolder,'model_snapshot.mat','modelSnapshot');
seismicModel=readVariable(seismicFolder,'model_snapshot.mat','modelSnapshot');
assert(isequal(model.mesh.nodes.id,seismicModel.mesh.nodes.id)&& ...
    isequal(model.mesh.nodes.xyz,seismicModel.mesh.nodes.xyz), ...
    'journal:GeometryMismatch','The corrected runs do not share the same geometry.');
configuration=readVariable(modalFolder,'configuration.mat','configuration');
seismicConfiguration=readVariable(seismicFolder,'configuration.mat','configuration');
results=readVariable(modalFolder,'results.mat','results');
operators=readVariable(modalFolder,'operators.mat','operators');
equilibrium=readVariable(modalFolder,'equilibrium.mat','equilibrium');
seismic=load(fullfile(seismicFolder,'action09_matrices.mat'), ...
    'responseStationary','responseRotating','action09Results','convergenceResponses');
speeds=double(results.modal.speedRPM(:));nSpeed=numel(speeds);
branchCount=size(results.modal.frequencyHz,2);nodeIds=[129;130;56;92;128];
assert(nSpeed==9&&branchCount==12,'journal:UnexpectedSpectrum', ...
    'The requested evidence consists of nine speeds and twelve stored branches.');
assert(all(isfinite(results.modal.frequencyHz),'all'), ...
    'journal:IncompleteBranches','All twelve stored branches must be finite.');

evidence=struct('schemaVersion','1.0.0','extractionPolicy', ...
    'Named persisted MAT variables only; no solvers rerun', ...
    'generatedUTC',char(datetime('now','TimeZone','UTC', ...
    'Format','yyyy-MM-dd''T''HH:mm:ss''Z''')), ...
    'projectRoot',projectRoot,'sourceRuns',struct( ...
    'correctedModal',modalRelative,'correctedSeismic',seismicRelative));
evidence.conventions=struct('nullValues','Unavailable or not applicable, never assumed zero', ...
    'nodalCoordinateOrder',{{'ux','uy','uz','theta_x','theta_y','theta_z'}}, ...
    'translationAxes',{{'global X','global Y','global Z'}}, ...
    'frequencies','Damped frequencies abs(imag(lambda))/(2*pi), Hz; tracked branch order', ...
    'naturalFrequency','Pole magnitude abs(lambda)/(2*pi), Hz, not a separately solved undamped spectrum', ...
    'stabilityScope','Only twelve selected stored branches; no branch 13 or uncomputed-spectrum claim', ...
    'seismicScope','Frozen operating-point operators and snapshot T/Tdot/Tddot recovery; not an LTV rotor trajectory', ...
    'operatorNormUnits','Whole-matrix Frobenius norms use the recorded SI coordinates and mix translational and rotational units; not a homogeneous physical scalar');

el=model.mesh.elements;primary=operators.operatingPoints{1};
evidence.geometry=struct('source',[modalRelative '/model_snapshot.mat:modelSnapshot'], ...
    'nodeCount',numel(model.mesh.nodes.id),'flexibleElementCount',numel(el.id), ...
    'fullDofCount',size(primary.full.M,1), ...
    'independentBeforeSupports',size(primary.reduced.constraintTc,2), ...
    'analysisDofCount',size(primary.reduced.M,1), ...
    'nodeIds',double(model.mesh.nodes.id(:)), ...
    'nodeCoordinates_m',double(model.mesh.nodes.xyz), ...
    'elementColumns',{{'id','nodeI','nodeJ','section','blade'}}, ...
    'elements',double([el.id(:),el.nodeI(:),el.nodeJ(:),el.section(:),el.blade(:)]), ...
    'elementTypes',string(el.type(:)),'summary',model.summary, ...
    'rotorAxis',model.rotorAxis,'selectedNodeIds',nodeIds);
evidence.operatingConfiguration=struct('rotor',configuration.rotor, ...
    'gravity',configuration.gravity,'drivetrain',configuration.drivetrain, ...
    'damping',configuration.damping,'aerodynamics',configuration.aerodynamics, ...
    'scope','Corrected prestressed operating sweep; not the unloaded historical ROM comparison');

modal=struct('source',[modalRelative '/results.mat:results.modal'], ...
    'speed_rpm',speeds,'branchIds',1:branchCount, ...
    'dampedFrequency_Hz',results.modal.frequencyHz, ...
    'poleMagnitudeFrequency_Hz',results.modal.naturalFrequencyHz, ...
    'dampingRatio',results.modal.dampingRatio, ...
    'lambdaReal_per_s',real(results.modal.eigenvalues), ...
    'lambdaImag_rad_s',imag(results.modal.eigenvalues), ...
    'effectiveTrackingMAC',results.modal.trackingMAC, ...
    'individualTrackingMAC',results.modal.individualTrackingMAC, ...
    'subspaceTrackingMAC',results.modal.subspaceTrackingMAC, ...
    'trackingAssignment',results.modal.trackingAssignment, ...
    'trackingClusterId',results.modal.trackingClusterId, ...
    'trackingRelativeFrequencyChange',results.modal.trackingFrequencyChange, ...
    'trackingMetric','Recorded mean of adjacent transformed mass matrices; no new MAC is computed here', ...
    'qepResidualDefinition', ...
    'norm((lambda^2*M+lambda*D+K)*phi)/((abs(lambda)^2*norm(M,F)+abs(lambda)*norm(D,F)+norm(K,F))*norm(phi))', ...
    'qepResidual',zeros(nSpeed,branchCount),'leftResidual',zeros(nSpeed,branchCount), ...
    'spectrumComplete',false(nSpeed,1));
modal.storedGroupClassification=cell(nSpeed,1);
modal.classificationCaution= ...
    'Saved coordinate-group participation proxy; these labels alone do not establish a local bending/torsion/free-spin physical mode.';
eqPoints=cell(nSpeed,1);operatorPoints=cell(nSpeed,1);
for i=1:nSpeed
    rpm=speeds(i);solution=results.modal.solutions{i};
    assert(numel(solution.residual)==branchCount,'journal:ResidualShape', ...
        'Residuals must refer to the same twelve selected tracked modes.');
    modal.qepResidual(i,:)=solution.residual(:).';
    modal.leftResidual(i,:)=solution.leftResidual(:).';
    modal.spectrumComplete(i)=solution.spectrumComplete;
    modal.storedGroupClassification{i}=results.modal.classification{i};
    point=atSpeed(operators.operatingPoints,rpm);
    state=atSpeed(equilibrium.operatingPoints,rpm);
    translations=reshape(state.qFull(model.dofs.node(:,1:3)),[],3);
    rotations=reshape(state.qFull(model.dofs.node(:,4:6)),[],3);
    [maxTranslation,nodeRow]=max(vecnorm(translations,2,2));
    [~,selectedRows]=ismember(nodeIds,double(model.mesh.nodes.id(:)));
    assert(all(selectedRows>0),'journal:SelectedNode','Missing requested node.');
    eqPoints{i}=struct('speed_rpm',rpm,'converged',logical(state.converged), ...
        'iterations',state.iterations,'relativeEquilibriumResidual',state.residualRelative, ...
        'maxNodalTranslationNorm_m',maxTranslation, ...
        'maxTranslationNodeId',double(model.mesh.nodes.id(nodeRow)), ...
        'maxAbsTranslationComponent_m',max(abs(translations),[],'all'), ...
        'translationalFieldL2Norm_m',norm(translations,'fro'), ...
        'maxNodalRotationNorm_rad',max(vecnorm(rotations,2,2)), ...
        'selectedNodeIds',nodeIds,'selectedTranslationXYZ_m',translations(selectedRows,:), ...
        'elementIds',double(el.id(:)),'elementAxialForce_N',state.elementAxialForces(:), ...
        'elementGravityReferenceAxialForce_N',state.elementGravityAxialForces(:), ...
        'elementCentrifugalAxialDifference_N',state.elementCentrifugalAxialForces(:), ...
        'axialSign','Positive tension; centrifugal difference is against the zero-speed gravity equilibrium', ...
        'axialExtremaByType',{axialExtrema(el,state.elementAxialForces)}, ...
        'globalBalanceError',state.globalBalanceError, ...
        'algebraicBalanceError',state.algebraicBalanceError);
    assert(isscalar(eqPoints{i}),'journal:EquilibriumShape', ...
        'Each equilibrium speed must export exactly one record.');
    gyro=point.diagnostics.gyroscopic;
    operatorPoints{i}=struct('speed_rpm',rpm, ...
        'fullGyroscopicFrobeniusNorm',norm(point.full.G,'fro'), ...
        'distributedGyroscopicFrobeniusNorm',gyro.distributedNorm, ...
        'rigidGyroscopicFrobeniusNorm',gyro.rigidNorm, ...
        'externalGyroscopicFrobeniusNorm',gyro.externalNorm, ...
        'fullMassRateFrobeniusNorm',norm(point.full.massRate,'fro'), ...
        'fullKtransportFrobeniusNorm',norm(point.full.Ktransport,'fro'), ...
        'reducedMassRateFrobeniusNorm',norm(point.reduced.massRate,'fro'), ...
        'constraintD_FrobeniusNorm',norm(point.reduced.constraintD,'fro'), ...
        'constraintK_FrobeniusNorm',norm(point.reduced.constraintK,'fro'), ...
        'gyroscopicSkewResidual',gyro.skewError, ...
        'massRateIdentityResidual',point.diagnostics.massRateIdentityError, ...
        'coordinateFrame',point.diagnostics.coordinateFrame, ...
        'linearizationScope',point.diagnostics.linearizationScope, ...
        'elementGyroscopicDiagnostics',gyro.elements, ...
        'bodyGyroscopicDiagnostics',gyro.bodies, ...
        'bladeIds',gyro.bladeIds,'bladeGyroscopicFrobeniusNorm',gyro.bladeNorms, ...
        'rayleigh',point.diagnostics.damping.rayleigh);
end
evidence.modal=modal;
evidence.equilibrium=struct('source',[modalRelative '/equilibrium.mat:equilibrium.operatingPoints'], ...
    'points',{eqPoints});
evidence.operators=struct('source',[modalRelative '/operators.mat:operators.operatingPoints'], ...
    'normConvention',evidence.conventions.operatorNormUnits,'points',{operatorPoints});
evidence.modalGates=gateEvidence(results.action08);

responses={seismic.responseStationary,seismic.responseRotating};
seismicCases=cell(2,1);
for k=1:2
    response=responses{k};nodes=cell(numel(nodeIds),1);
    for j=1:numel(nodeIds)
        row=find(double(seismicModel.mesh.nodes.id(:))==nodeIds(j));
        dofs=seismicModel.dofs.node(row,1:3);
        displacement=response.qFull(dofs,:).';acceleration=response.absoluteAccelerationFull(dofs,:).';
        nodes{j}=struct('nodeId',nodeIds(j),'displacementRelative_m',displacement, ...
            'accelerationAbsolute_m_s2',acceleration, ...
            'peakAbsDisplacementXYZ_m',max(abs(displacement),[],1), ...
            'peakAbsAccelerationXYZ_m_s2',max(abs(acceleration),[],1));
    end
    record=response.accelerogram;
    baseRow=find(double(seismicModel.mesh.nodes.id(:))==1);
    reaction=struct('available',false,'nodeId',1,'momentY_Nm',[], ...
        'peakAbsMomentY_Nm',NaN,'source','unavailable');
    if isfield(response,'constraintForcesFull')&&~isempty(response.constraintForcesFull)
        values=response.constraintForcesFull(seismicModel.dofs.node(baseRow,5),:).';
        reaction=struct('available',true,'nodeId',1,'momentY_Nm',values, ...
            'peakAbsMomentY_Nm',max(abs(values)), ...
            'source','stored constraintForcesFull, base-node theta_y row; complete equilibrium residual');
    end
    seismicCases{k}=struct('speed_rpm',response.speedRPM,'time_s',response.t(:), ...
        'timeStep_s',mean(diff(response.t)),'sampleCount',numel(response.t), ...
        'groundComponentDirections',response.directions, ...
        'groundDisplacement_m',record.displacement, ...
        'groundVelocity_m_s',record.velocity,'groundAcceleration_m_s2',record.acceleration, ...
        'groundProcessing',record.processing,'nodes',{nodes},'baseReaction',reaction, ...
        'integrationMetadata',response.integrationMetadata, ...
        'snapshotMetadata',response.snapshotMetadata, ...
        'relativeProjectedResidual',response.reactionDiagnostics.relativeProjectedResidual, ...
        'maximumNewmarkResidual',max(response.relativeResidual), ...
        'maximumAlgorithmicEnergyBalanceResidual',max(response.energy.relativeBalanceError), ...
        'newmark',struct('beta',response.beta,'gamma',response.gamma));
end
convergence=cell(numel(seismic.convergenceResponses),1);
for k=1:numel(convergence)
    response=seismic.convergenceResponses{k};
    nodeId=seismicConfiguration.action09.convergenceNodeId;
    row=find(double(seismicModel.mesh.nodes.id(:))==nodeId);
    labels=["ux","uy","uz","theta_x","theta_y","theta_z"];
    component=string(seismicConfiguration.action09.convergenceComponent);
    col=find(labels==component);dof=seismicModel.dofs.node(row,col);
    convergence{k}=struct('speed_rpm',response.speedRPM, ...
        'timeStep_s',mean(diff(response.t)),'time_s',response.t(:), ...
        'nodeId',nodeId,'component',component,'displacement_m',response.qFull(dof,:).');
end
evidence.seismic=struct('source',[seismicRelative '/action09_matrices.mat'], ...
    'recordStatus',seismicConfiguration.seismic.recordStatus, ...
    'recordDescription',seismicConfiguration.seismic.record.description, ...
    'cases',{seismicCases},'temporalConvergence',tableColumns(seismic.action09Results.timeConvergenceTable), ...
    'convergenceHistories',{convergence},'gates',gateEvidence(seismic.action09Results));

evidence.stationaryHistorical=historicalComparison(projectRoot);
evidence.rigidModeHistorical=historicalRigidModes(projectRoot);
evidence.meshRefinementHistorical=historicalMesh(projectRoot);
evidence.shapes=struct('modalArrays',[nSpeed branchCount], ...
    'equilibriumSelectedTranslationsPerSpeed',[numel(nodeIds) 3], ...
    'axialForcesPerSpeed',numel(el.id),'seismicCaseCount',2, ...
    'seismicXYZHistoryPerNode',[numel(responses{1}.t) 3], ...
    'seismicSelectedNodeCount',numel(nodeIds), ...
    'temporalConvergenceCases',numel(convergence));
parent=fileparts(outputFile);if ~isfolder(parent),mkdir(parent);end
evidence=jsonReady(evidence);
json=jsonencode(evidence,'PrettyPrint',false,'ConvertInfAndNaN',true);
fid=fopen(outputFile,'w','n','UTF-8');
if fid<0,error('journal:WriteFailure','Cannot open %s.',outputFile);end
cleanup=onCleanup(@()fclose(fid));fprintf(fid,'%s\n',json);clear cleanup
decoded=jsondecode(fileread(outputFile));
assert(isequal(size(decoded.modal.dampedFrequency_Hz),[9 12]), ...
    'journal:JSONShape','Round-trip JSON changed the modal array shape.');
assert(numel(decoded.equilibrium.points)==9&& ...
    isscalar(decoded.equilibrium.points(1).speed_rpm), ...
    'journal:JSONShape','Round-trip JSON changed the equilibrium records.');
fprintf('Wrote %s (%d JSON characters).\n',outputFile,numel(json));
fprintf('Geometry: %d nodes, %d beams, DOFs full/MPC/free %d/%d/%d.\n', ...
    evidence.geometry.nodeCount,evidence.geometry.flexibleElementCount, ...
    evidence.geometry.fullDofCount,evidence.geometry.independentBeforeSupports, ...
    evidence.geometry.analysisDofCount);
fprintf('Modal: %d speeds x %d branches; max QEP residual %.16g.\n', ...
    nSpeed,branchCount,max(modal.qepResidual,[],'all'));
fprintf('Frequency at first/last speed (Hz), followed by damping ratio at last speed:\n');
disp([modal.branchIds(:),modal.dampedFrequency_Hz([1 end],:).',modal.dampingRatio(end,:).']);
fprintf('Equilibrium maxima (rpm, max nodal translation m, node, residual):\n');
for k=1:nSpeed
    p=eqPoints{k};fprintf('%.8g %.16g %g %.16g\n',p.speed_rpm, ...
        p.maxNodalTranslationNorm_m,p.maxTranslationNodeId,p.relativeEquilibriumResidual);
end
fprintf('Seismic gate metrics:\n');disp(seismic.action09Results.metrics);
for k=1:2
    s=seismicCases{k};fprintf('Seismic %.1f rpm: %d samples, dt %.9g s, peak |base My| %.16g Nm.\n', ...
        s.speed_rpm,s.sampleCount,s.timeStep_s,s.baseReaction.peakAbsMomentY_Nm);
end
end

function value=readVariable(folder,file,name)
source=load(fullfile(folder,file),name);
assert(isfield(source,name),'journal:MissingVariable','%s lacks %s.',file,name);
value=source.(name);
end

function point=atSpeed(points,rpm)
if isstruct(points),points=num2cell(points);end
speeds=cellfun(@(p)double(p.speedRPM),points);
index=find(abs(speeds-rpm)<1e-10);
assert(numel(index)==1,'journal:SpeedIdentity','Speed %.12g is missing or ambiguous.',rpm);
point=points{index};
end

function rows=axialExtrema(elements,force)
types=unique(string(elements.type(:)),'stable');rows=cell(numel(types),1);
for k=1:numel(types)
    active=find(string(elements.type(:))==types(k));
    [lo,i]=min(force(active));[hi,j]=max(force(active));
    rows{k}=struct('componentType',types(k),'minimum_N',lo,'maximum_N',hi, ...
        'minimumElementId',double(elements.id(active(i))), ...
        'maximumElementId',double(elements.id(active(j))));
end
end

function evidence=gateEvidence(suite)
evidence=struct('passed',logical(suite.passed),'scope',suite.scope, ...
    'metrics',suite.metrics,'checks',suite.checks);
end

function out=tableColumns(value)
out=struct('rowCount',height(value),'columnOrder',{value.Properties.VariableNames}, ...
    'columns',table2struct(value,'ToScalar',true));
end

function evidence=historicalComparison(root)
relative='runs/run_20260914_mecom_comparison';folder=fullfile(root,relative);
raw=load(fullfile(folder,'global_raw_data.mat'),'parameters','t','ug','vg','ag', ...
    'outputValues','Yfine','timeConvergence');
summary=load(fullfile(folder,'comparison_summary.mat'),'costTable','globalTable');
modelNames=string(summary.costTable.model(:));
outputNames=unique(string(summary.globalTable.output),'stable');
assert(numel(modelNames)==numel(raw.outputValues)&&numel(outputNames)==8, ...
    'journal:HistoricalShape','Historical outputs and stored labels do not align.');
values=cell(numel(modelNames),1);units=[repmat("m",5,1);"m/s^2";"m/s^2";"N m"];
for k=1:numel(modelNames)
    assert(isequal(size(raw.outputValues{k}),[8 numel(raw.t)]), ...
        'journal:HistoricalShape','Historical output dimensions changed.');
    values{k}=struct('modelName',modelNames(k),'valuesTimeByOutput',raw.outputValues{k}.');
end
evidence=struct('source',[relative '/global_raw_data.mat'], ...
    'labelSource',[relative '/comparison_summary.mat:costTable,globalTable'], ...
    'scope','Separate historical zero-speed, gravity-off, unprestressed modal-reduction benchmark; not the corrected prestressed Campbell or 1 s seismic run', ...
    'parameters',raw.parameters,'time_s',raw.t(:),'groundDisplacement_m',raw.ug, ...
    'groundVelocity_m_s',raw.vg,'groundAcceleration_m_s2',raw.ag, ...
    'outputNames',outputNames,'outputUnits',units,'models',{values}, ...
    'finerFullModelValuesAtCoarseTimes',raw.Yfine.', ...
    'temporalConvergence',tableColumns(raw.timeConvergence), ...
    'shapeTimeByOutput',size(raw.outputValues{1}.'));
end

function evidence=historicalRigidModes(root)
relative='runs/run_20260914_mecom_rigid_modes/rigid_mode_evidence.mat';
stored=load(fullfile(root,relative),'summary','spectra','singular','precision');
nearZero=stored.spectra(stored.spectra.absoluteSortedIndex<=18,:);
evidence=struct('source',relative, ...
    'scope','Historical zero-speed unloaded rigid-kernel study; raw and analytically imposed zero blocks remain explicitly distinguished', ...
    'summary',tableColumns(stored.summary),'precision',stored.precision, ...
    'nearZeroSpectra',tableColumns(nearZero), ...
    'stiffnessSingularValues',tableColumns(stored.singular));
end

function evidence=historicalMesh(root)
relative='runs/run_20260914_mecom_mesh_refinement/mesh_study.mat';
stored=load(fullfile(root,relative),'study');
evidence=struct('source',relative,'scope',stored.study.description, ...
    'summary',tableColumns(stored.study.summary), ...
    'frequencies',tableColumns(stored.study.frequencies));
end

function value=jsonReady(value)
% Stored equilibrium vectors and some diagnostics remain sparse. Preserve
% their values, making only the small exported slices JSON-compatible.
if isnumeric(value)||islogical(value)
    if issparse(value),value=full(value);end
    assert(isreal(value),'journal:ComplexJSON', ...
        'Complex data must be exported as explicitly named real/imaginary parts.');
elseif isstruct(value)
    names=fieldnames(value);
    for index=1:numel(value)
        for j=1:numel(names)
            value(index).(names{j})=jsonReady(value(index).(names{j}));
        end
    end
elseif iscell(value)
    for index=1:numel(value),value{index}=jsonReady(value{index});end
elseif ~(ischar(value)||isstring(value))
    error('journal:UnsupportedJSON','Unsupported exported type %s.',class(value));
end
end
