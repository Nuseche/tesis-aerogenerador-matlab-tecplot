function summary=response_summary(result)
%RESPONSE_SUMMARY Report late-window mean, half range and a detrended FFT peak.
t=result.t;x=result.tipWindDisplacement;tail=t>=max(t(1),t(end)*.75);y=x(tail);tt=t(tail);
frequency=NaN;
if numel(y)>8
    z=detrend(y);spectrum=abs(fft(z.*(.5-.5*cos(2*pi*(0:numel(z)-1)'/(numel(z)-1)))));
    bins=2:floor(numel(z)/2);[~,j]=max(spectrum(bins));frequency=2*pi*(bins(j)-1)/(numel(z)*mean(diff(tt)));
end
summary=struct('lateWindowStart_s',tt(1),'lateWindowEnd_s',tt(end),'mean_m',mean(y), ...
    'halfRange_m',(max(y)-min(y))/2,'dominantFrequency_radps',frequency, ...
    'maximumDisplacement_m',max(abs(x)),'maximumElasticRotation_rad',result.maximumAcceptedRotation, ...
    'maximumMechanicalResidual',result.maximumMechanicalResidual,'runtime_s',result.elapsedSeconds, ...
    'feedback',result.feedback,'aerodynamicEvaluations',result.aerodynamicEvaluations, ...
    'status',result.status,'terminationTime_s',result.terminationTime, ...
    'steadyStateEstablished',false,'frequencyInterpretation',"detrended late-window spectrum; not automatically flutter or a converged limit cycle", ...
    'aerodynamicModel',"quasi-steady reference polars with no wake induction unless explicitly supplied");
end
