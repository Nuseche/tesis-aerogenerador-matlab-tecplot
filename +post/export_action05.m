function artifacts=export_action05(run,action05)
%EXPORT_ACTION05 Export stored mass-formulation comparison tables.
arguments
    run (1,1) struct
    action05 (1,1) struct
end
mapping={ ...
    'checkTable','action05_validation.csv'; ...
    'massComparisonTable','action05_mass_comparison.csv'; ...
    'modalComparisonTable','action05_modal_comparison.csv'; ...
    'diagnosticsTable','action05_diagnostics.csv'};
for index=1:size(mapping,1)
    field=mapping{index,1};file=mapping{index,2};
    if ~isfield(action05,field)||~istable(action05.(field))
        error('post:export_action05:MissingTable', ...
            'Action 05 result is missing table %s.',field);
    end
    writetable(action05.(field),fullfile(run.folder,file));
end
artifacts=struct('validation',action05.checkTable, ...
    'massComparison',action05.massComparisonTable, ...
    'modalComparison',action05.modalComparisonTable, ...
    'diagnostics',action05.diagnosticsTable);
end
