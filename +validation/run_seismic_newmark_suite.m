function suite=run_seismic_newmark_suite(modelData,reduced,sweep, ...
        responses,convergenceResponses,elementForces,cfg)
%RUN_SEISMIC_NEWMARK_SUITE Specialized Action-09 acceptance verification.

seriesTol=value(cfg,{'action09','seriesTolerance'},1e-12);
kinTol=value(cfg,{'action09','kinematicTolerance'},1e-12);
massTol=value(cfg,{'action09','massProjectionTolerance'},1e-12);
forceTol=value(cfg,{'action09','forceIdentityTolerance'},1e-14);
sdofTol=value(cfg,{'action09','sdofErrorTolerance'},1e-4);
minimumSdofOrder=value(cfg,{'action09','minimumSdofOrder'},1.9);
superpositionTol=value(cfg,{'action09','superpositionTolerance'},1e-10);
residualTol=value(cfg,{'action09','dynamicResidualTolerance'},1e-9);
benchmarkEnergyTol=value(cfg,{'action09','benchmarkEnergyTolerance'},1e-8);
modelEnergyTol=value(cfg,{'action09','modelEnergyTolerance'},1e-6);
projectedTol=value(cfg,{'action09','projectedEquilibriumTolerance'},1e-9);
elementTol=value(cfg,{'action09','elementBackwardTolerance'},1e-12);
assemblyTol=value(cfg,{'action09','elementAssemblyTolerance'},1e-12);
minimumModelOrder=value(cfg,{'action09','minimumModelOrder'},1.8);
fineRelativeTol=value(cfg,{'action09','fineRelativeDifferenceTolerance'},1e-3);
fineMaximumTol=value(cfg,{'action09','fineMaximumDifferenceTolerance'},.01);
checks=repmat(makeCheck("",true,0,0,"",false),0,1);

[seriesError,unitPass,groundMotionTable]=groundMotionChecks( ...
    responses.rotating,cfg);
checks(end+1,1)=makeCheck("record.suppliedKinematicsPreserved", ...
    seriesError<=seriesTol,seriesError,seriesTol, ...
    "Processed ag/vg/ug reproduce the supplied analytic SI series.",true);
checks(end+1,1)=makeCheck("record.unitsSI",unitPass,double(~unitPass),0, ...
    "Time, acceleration, velocity, and displacement use coherent SI units.",true);
baselinePolicyPass=baselinePolicyCheck();
checks(end+1,1)=makeCheck("record.baselinePolicyExplicit",baselinePolicyPass, ...
    double(~baselinePolicyPass),0, ...
    "Baseline correction rejects incompatible supplied kinematics by default.",true);

responseNames=["stationary" "rotating"];
kinematicError=zeros(2,1);massProjectionError=zeros(2,1);
forceIdentityError=zeros(2,1);dynamicResidual=zeros(2,1);
energyError=zeros(2,1);absoluteError=zeros(2,1);
projectedResidual=zeros(2,1);finiteResponse=true;
for index=1:2
    response=responses.(responseNames(index));
    kinematicError(index)=response.influenceDiagnostics.kinematic. ...
        relativeCompatibilityError;
    massProjectionError(index)=response.influenceDiagnostics.massProjection. ...
        relativeMassProjectionError;
    forceIdentityError(index)=relative(response.baseForce+ ...
        response.baseForceOperator*response.accelerogram.acceleration.', ...
        response.baseForce);
    dynamicResidual(index)=max(response.relativeResidual(2:end),[],'all');
    energyError(index)=max(response.energy.relativeBalanceError,[],'all');
    absoluteError(index)=absoluteKinematicError(response);
    projectedResidual(index)=response.reactionDiagnostics.relativeProjectedResidual;
    finiteResponse=finiteResponse&&all(isfinite(response.q),'all')&& ...
        all(isfinite(response.qd),'all')&&all(isfinite(response.qdd),'all')&& ...
        all(isfinite(response.absoluteAccelerationFull),'all');
end
checks(end+1,1)=makeCheck("influence.kinematicCompatibility", ...
    max(kinematicError)<=kinTol,max(kinematicError),kinTol, ...
    "Tc*GammaKinematic equals the relative compatible full field.",true);
checks(end+1,1)=makeCheck("influence.massConsistentProjection", ...
    max(massProjectionError)<=massTol,max(massProjectionError),massTol, ...
    "Mr*GammaEffective equals Tc'*Mfull*Rfull.",true);
checks(end+1,1)=makeCheck("loading.baseForceSignAndSum", ...
    max(forceIdentityError)<=forceTol,max(forceIdentityError),forceTol, ...
    "Base force is exactly -Mr*GammaEffective*ag.",true);
checks(end+1,1)=makeCheck("response.dynamicResidual", ...
    max(dynamicResidual)<=residualTol,max(dynamicResidual),residualTol, ...
    "Reduced Newmark equilibrium residual, excluding the initial state.",true);
checks(end+1,1)=makeCheck("response.energyBalance", ...
    max(energyError)<=modelEnergyTol,max(energyError),modelEnergyTol, ...
    "Newmark-compatible energy balance for both operating points.",true);
checks(end+1,1)=makeCheck("response.absoluteKinematics", ...
    max(absoluteError)<=kinTol,max(absoluteError),kinTol, ...
    "Reduced and full absolute states equal relative state plus ground motion.",true);
checks(end+1,1)=makeCheck("constraints.projectedEquilibrium", ...
    max(projectedResidual)<=projectedTol,max(projectedResidual),projectedTol, ...
    "Tc' times the complete generalized constraint force is zero.",true);
checks(end+1,1)=makeCheck("response.allFinite",finiteResponse, ...
    double(~finiteResponse),0,"Every stationary and rotating state is finite.",true);

supportSeparation=supportReactionCheck(responses.rotating,modelData);
checks(end+1,1)=makeCheck("constraints.supportRowsSeparated", ...
    supportSeparation,double(~supportSeparation),0, ...
    "Fixed-support reactions are an explicit subset of the full constraint force.",true);

[sdofMetrics,sdofBenchmarkTable]=sdofBenchmark();
checks(end+1,1)=makeCheck("benchmark.sdofFineError", ...
    sdofMetrics.fineError<=sdofTol,sdofMetrics.fineError,sdofTol, ...
    "Harmonic base-excitation SDOF versus its closed-form response.",true);
checks(end+1,1)=makeCheck("benchmark.sdofSecondOrder", ...
    sdofMetrics.minimumOrder>=minimumSdofOrder,sdofMetrics.minimumOrder, ...
    minimumSdofOrder,"Observed temporal order of average-acceleration Newmark.",true);
checks(end+1,1)=makeCheck("benchmark.unstableParametersRejected", ...
    sdofMetrics.unstableRejected,double(~sdofMetrics.unstableRejected),0, ...
    "Conditionally stable Newmark parameters are rejected by default.",true);
checks(end+1,1)=makeCheck("benchmark.conservativeEnergy", ...
    sdofMetrics.conservativeEnergyError<=benchmarkEnergyTol, ...
    sdofMetrics.conservativeEnergyError,benchmarkEnergyTol, ...
    "Discrete energy is conserved in an undamped oscillator.",true);
checks(end+1,1)=makeCheck("benchmark.dampedEnergy", ...
    sdofMetrics.dampedEnergyError<=benchmarkEnergyTol, ...
    sdofMetrics.dampedEnergyError,benchmarkEnergyTol, ...
    "Damping work closes the discrete energy balance.",true);
superpositionError=superpositionBenchmark();
checks(end+1,1)=makeCheck("benchmark.multicomponentSuperposition", ...
    superpositionError<=superpositionTol,superpositionError,superpositionTol, ...
    "The linear response to two components equals the sum of separate responses.",true);

backwardError=elementForces.maximumLocalGlobalBackwardError;
assemblyError=elementForces.assemblyError;
checks(end+1,1)=makeCheck("elements.localGlobalBackwardError", ...
    backwardError<=elementTol,backwardError,elementTol, ...
    "Local/global Timoshenko end forces satisfy a backward-error identity.",true);
checks(end+1,1)=makeCheck("elements.globalAssembly", ...
    assemblyError<=assemblyTol,assemblyError,assemblyTol, ...
    "Assembled element forces equal the assembled elastic beam operator.",true);

[convergenceMetrics,timeConvergenceTable]=convergenceChecks( ...
    modelData,convergenceResponses,cfg);
checks(end+1,1)=makeCheck("convergence.monotoneWaveformDifference", ...
    convergenceMetrics.monotone,double(~convergenceMetrics.monotone),0, ...
    "Successive waveform differences decrease under time-step refinement.",true);
checks(end+1,1)=makeCheck("convergence.modelTemporalOrder", ...
    convergenceMetrics.observedOrder>=minimumModelOrder, ...
    convergenceMetrics.observedOrder,minimumModelOrder, ...
    "Full-model response exhibits second-order temporal convergence.",true);
checks(end+1,1)=makeCheck("convergence.fineRelativeDifference", ...
    convergenceMetrics.fineRelativeDifference<=fineRelativeTol, ...
    convergenceMetrics.fineRelativeDifference,fineRelativeTol, ...
    "Relative waveform difference between the two finest meshes.",true);
checks(end+1,1)=makeCheck("convergence.fineMaximumDifference", ...
    convergenceMetrics.fineMaximumDifference<=fineMaximumTol, ...
    convergenceMetrics.fineMaximumDifference,fineMaximumTol, ...
    "Selected physical response extremum changes by at most one percent.",true);

[operatorMetrics,operatorTable]=operatorChecks(sweep);
checks(end+1,1)=makeCheck("operators.sparse",operatorMetrics.allSparse, ...
    double(~operatorMetrics.allSparse),0,"All stored full/reduced operators are sparse.",true);
checks(end+1,1)=makeCheck("operators.finite",operatorMetrics.allFinite, ...
    double(~operatorMetrics.allFinite),0,"All operator nonzeros are finite.",true);
checks(end+1,1)=makeCheck("operators.gyroZeroAtRest", ...
    operatorMetrics.zeroGyroNorm==0,operatorMetrics.zeroGyroNorm,0, ...
    "G is exactly zero at 0 RPM.",true);
checks(end+1,1)=makeCheck("operators.gyroPresentAtRotation", ...
    operatorMetrics.rotatingGyroNorm>0,operatorMetrics.rotatingGyroNorm,0, ...
    "Distributed and rigid gyroscopy are present at 12 RPM.",true);
checks(end+1,1)=makeCheck("operators.stiffnessLedger", ...
    operatorMetrics.stiffnessIdentity<=kinTol, ...
    operatorMetrics.stiffnessIdentity,kinTol, ...
    "Ke, Kg, KOmega, and Kaero are each included exactly once.",true);

traceabilityPass=isfield(cfg.seismic,'recordStatus')&& ...
    string(cfg.seismic.recordStatus)=="synthetic_verification_not_design_accelerogram"&& ...
    isfield(cfg.drivetrain,'calibrationStatus')&& ...
    contains(string(cfg.drivetrain.calibrationStatus),"not_physical")&& ...
    isfield(cfg.damping,'calibrationStatus')&& ...
    contains(string(cfg.damping.calibrationStatus),"not_physical")&& ...
    isfield(cfg.aerodynamics,'status')&&isfield(reduced,'Tc')&& ...
    size(reduced.Tc,1)==double(modelData.dofs.number);
checks(end+1,1)=makeCheck("traceability.benchmarkLabels",traceabilityPass, ...
    double(~traceabilityPass),0, ...
    "Ground motion, drivetrain, damping, and aerodynamic status remain explicit.",true);

responseExtremaTable=responseExtrema(modelData,responses,cfg);
reactionsTable=reactionSummary(modelData,responses.rotating);
elementForcesTable=elementSummary(elementForces);
suite=struct('schemaVersion',"1.0.0", ...
    'scope',"linearized_multicomponent_seismic_response_at_frozen_operating_point", ...
    'checks',checks,'checkTable',struct2table(checks), ...
    'groundMotionTable',groundMotionTable, ...
    'timeConvergenceTable',timeConvergenceTable, ...
    'sdofBenchmarkTable',sdofBenchmarkTable, ...
    'responseExtremaTable',responseExtremaTable, ...
    'reactionsTable',reactionsTable,'elementForcesTable',elementForcesTable, ...
    'operatorTable',operatorTable, ...
    'metrics',struct('maximumSeriesError',seriesError, ...
    'maximumKinematicCompatibilityError',max(kinematicError), ...
    'maximumMassProjectionError',max(massProjectionError), ...
    'maximumBaseForceIdentityError',max(forceIdentityError), ...
    'maximumDynamicResidual',max(dynamicResidual), ...
    'maximumModelEnergyError',max(energyError), ...
    'maximumAbsoluteKinematicError',max(absoluteError), ...
    'maximumProjectedEquilibriumResidual',max(projectedResidual), ...
    'sdofFineError',sdofMetrics.fineError, ...
    'minimumSdofOrder',sdofMetrics.minimumOrder, ...
    'superpositionError',superpositionError, ...
    'elementBackwardError',backwardError,'elementAssemblyError',assemblyError, ...
    'modelTemporalOrder',convergenceMetrics.observedOrder, ...
    'fineRelativeDifference',convergenceMetrics.fineRelativeDifference, ...
    'fineMaximumDifference',convergenceMetrics.fineMaximumDifference, ...
    'zeroSpeedGyroNorm',operatorMetrics.zeroGyroNorm, ...
    'rotatingGyroNorm',operatorMetrics.rotatingGyroNorm));
suite.passed=all([checks.pass]|~[checks.critical]);
suite.criticalFailures=checks(~[checks.pass]&[checks.critical]);
if logical(value(cfg,{'validation','failOnCritical'},1))&&~suite.passed
    names=strjoin(string({suite.criticalFailures.name}),', ');
    error('validation:run_seismic_newmark_suite:CriticalFailure', ...
        'Action 09 critical checks failed: %s',names);
end
end

function [errorValue,unitPass,tableValue]=groundMotionChecks(response,cfg)
record=response.accelerogram;source=cfg.seismic.record;t=record.t(:);
scale=double(cfg.seismic.scaleFactor);
expectedA=scale*interp1(source.t,source.acceleration,t,cfg.seismic.interpolation);
expectedV=scale*interp1(source.t,source.velocity,t,cfg.seismic.interpolation);
expectedU=scale*interp1(source.t,source.displacement,t,cfg.seismic.interpolation);
errorValue=max([relative(record.acceleration-expectedA,expectedA), ...
    relative(record.velocity-expectedV,expectedV), ...
    relative(record.displacement-expectedU,expectedU)]);
unitPass=string(record.timeUnit)=="s"&& ...
    string(record.accelerationUnit)=="m/s^2"&& ...
    string(record.velocityUnit)=="m/s"&&string(record.displacementUnit)=="m";
tableValue=table(t,'VariableNames',{'time_s'});
for component=1:size(record.acceleration,2)
    tableValue.(sprintf('ag_%d_mps2',component))=record.acceleration(:,component);
    tableValue.(sprintf('vg_%d_mps',component))=record.velocity(:,component);
    tableValue.(sprintf('ug_%d_m',component))=record.displacement(:,component);
end
end

function pass=baselinePolicyCheck()
source=struct('t',[0;1],'acceleration',[1;2], ...
    'velocity',[0;1.5],'displacement',[0;.5]);
try
    io.load_accelerogram(source,struct('baselineCorrection',"mean"));
    pass=false;
catch exception
    pass=strcmp(exception.identifier, ...
        'io:Accelerogram:InconsistentProvidedKinematics');
end
end

function errorValue=absoluteKinematicError(response)
ug=response.accelerogram.displacement.';
vg=response.accelerogram.velocity.';
ag=response.accelerogram.acceleration.';
reducedErrors=[ ...
    relative(response.absoluteDisplacement-response.q- ...
        response.GammaKinematic*ug,response.absoluteDisplacement), ...
    relative(response.absoluteVelocity-response.qd- ...
        response.GammaKinematic*vg,response.absoluteVelocity), ...
    relative(response.absoluteAcceleration-response.qdd- ...
        response.GammaKinematic*ag,response.absoluteAcceleration)];
fullErrors=[ ...
    relative(response.absoluteDisplacementFull-response.qFull- ...
        response.GammaFull*ug,response.absoluteDisplacementFull), ...
    relative(response.absoluteVelocityFull-response.qdFull- ...
        response.GammaFull*vg,response.absoluteVelocityFull), ...
    relative(response.absoluteAccelerationFull-response.qddFull- ...
        response.GammaFull*ag,response.absoluteAccelerationFull)];
errorValue=max([reducedErrors fullErrors]);
end

function pass=supportReactionCheck(response,modelData)
fixed=double(modelData.dofs.fixed(:));
pass=isequal(response.reactions,response.constraintForcesFull(fixed,:))&& ...
    numel(unique(fixed))==numel(fixed)&& ...
    all(fixed>=1&fixed<=size(response.constraintForcesFull,1));
end

function [metrics,tableValue]=sdofBenchmark()
steps=[.04;.02;.01;.005];errors=zeros(size(steps));orders=nan(size(steps));
m=1.7;c=.25;k=11;omega=1.8;groundAmplitude=.8;
forceAmplitude=-m*groundAmplitude;
responseAmplitude=forceAmplitude/sqrt((k-m*omega^2)^2+(c*omega)^2);
phase=atan2(c*omega,k-m*omega^2);
for index=1:numel(steps)
    t=(0:steps(index):1.2).';force=forceAmplitude*sin(omega*t);
    q0=-responseAmplitude*sin(phase);
    qd0=responseAmplitude*omega*cos(phase);
    result=dynamics.newmark_integrate(m,c,k,t,force, ...
        struct('q0',q0,'qd0',qd0));
    exact=responseAmplitude*sin(omega*t-phase);
    errors(index)=max(abs(result.q(:)-exact));
    if index>1
        orders(index)=log(errors(index-1)/errors(index))/ ...
            log(steps(index-1)/steps(index));
    end
end
unstableRejected=false;
try
    dynamics.newmark_integrate(1,0,1,[0;.1],zeros(1,2), ...
        struct('beta',.1,'gamma',.1));
catch exception
    unstableRejected=strcmp(exception.identifier, ...
        'dynamics:Newmark:ConditionallyStableParameters');
end
t=(0:.002:1).';conservative=dynamics.newmark_integrate( ...
    1,0,4,t,zeros(size(t)),struct('q0',1));
damped=dynamics.newmark_integrate( ...
    1,.2,4,t,zeros(size(t)),struct('q0',1));
metrics=struct('fineError',errors(end),'minimumOrder',min(orders(2:end)), ...
    'unstableRejected',unstableRejected, ...
    'conservativeEnergyError',max(conservative.energy.relativeBalanceError), ...
    'dampedEnergyError',max(damped.energy.relativeBalanceError));
tableValue=table(steps,errors,orders, ...
    'VariableNames',{'dt_s','maximumDisplacementError','observedOrder'});
end

function errorValue=superpositionBenchmark()
t=(0:.01:.5).';M=[2 .1;.1 1.5];D=[.2 .05;-.02 .3];K=[8 .4;.2 10];
force1=[sin(3*t).';zeros(1,numel(t))];
force2=[zeros(1,numel(t));.7*cos(2*t).'];
combined=dynamics.newmark_integrate(M,D,K,t,force1+force2,struct());
first=dynamics.newmark_integrate(M,D,K,t,force1,struct());
second=dynamics.newmark_integrate(M,D,K,t,force2,struct());
errorValue=relative(combined.q-first.q-second.q,combined.q);
end

function [metrics,tableValue]=convergenceChecks(modelData,responses,cfg)
steps=double(cfg.action09.timeStepGrid(:));n=numel(steps);
nodeId=double(cfg.action09.convergenceNodeId);
component=componentIndex(cfg.action09.convergenceComponent);
row=find(double(modelData.mesh.nodes.id)==nodeId,1);
if isempty(row),error('validation:Action09:UnknownConvergenceNode', ...
        'Unknown convergence node %d.',nodeId);end
dof=double(modelData.dofs.node(row,component));maximum=zeros(n,1);
for index=1:n
    maximum(index)=max(abs(responses{index}.qFull(dof,:)));
end
difference=nan(n,1);order=nan(n,1);
for index=1:n-1
    coarse=responses{index};fine=responses{index+1};
    fineOnCoarse=interp1(fine.t,fine.qFull(dof,:).',coarse.t);
    difference(index)=norm(coarse.qFull(dof,:).'-fineOnCoarse)/ ...
        max(norm(fineOnCoarse),eps);
end
if n>=3
    for index=2:n-1
        order(index)=log(difference(index-1)/difference(index))/ ...
            log(steps(index-1)/steps(index));
    end
end
observedOrder=min(order(2:n-1),[],'omitnan');
fineMaximumDifference=abs(maximum(end-1)-maximum(end))/ ...
    max(maximum(end),eps);
metrics=struct('monotone',all(diff(difference(1:end-1))<0), ...
    'observedOrder',observedOrder, ...
    'fineRelativeDifference',difference(end-1), ...
    'fineMaximumDifference',fineMaximumDifference,'fullDof',dof);
nodeIdColumn=repmat(nodeId,n,1);componentColumn=repmat(string( ...
    cfg.action09.convergenceComponent),n,1);
tableValue=table(steps,nodeIdColumn,componentColumn,maximum,difference,order, ...
    'VariableNames',{'dt_s','nodeId','component','maximumAbsDisplacement_m', ...
    'relativeWaveformDifferenceToNext','observedOrder'});
end

function [metrics,tableValue]=operatorChecks(sweep)
n=numel(sweep.ops);speedRPM=zeros(n,1);normG=zeros(n,1);normKg=zeros(n,1);
normKOmega=zeros(n,1);identity=zeros(n,1);allSparse=true;allFinite=true;
for index=1:n
    ops=sweep.ops{index};speedRPM(index)=sweep.speedRPM(index);
    matrices={ops.full.M,ops.full.D,ops.full.K,ops.full.G,ops.full.Kg, ...
        ops.full.KOmega,ops.reduced.M,ops.reduced.D,ops.reduced.K, ...
        ops.reduced.G,ops.reduced.Kg,ops.reduced.KOmega};
    allSparse=allSparse&&all(cellfun(@issparse,matrices));
    allFinite=allFinite&&all(cellfun( ...
        @(matrix)all(isfinite(nonzeros(matrix))),matrices));
    normG(index)=norm(ops.full.G,'fro');normKg(index)=norm(ops.full.Kg,'fro');
    normKOmega(index)=norm(ops.full.KOmega,'fro');
    identity(index)=relative(ops.full.K-ops.full.Ke-ops.full.Kg- ...
        ops.full.KOmega-ops.full.Kaero-ops.full.Ktransport,ops.full.K);
end
zeroIndex=find(abs(speedRPM)<=eps,1);rotatingIndex=find(abs(speedRPM)>eps,1);
metrics=struct('allSparse',allSparse,'allFinite',allFinite, ...
    'zeroGyroNorm',normG(zeroIndex),'rotatingGyroNorm',normG(rotatingIndex), ...
    'stiffnessIdentity',max(identity));
tableValue=table(speedRPM,normG,normKg,normKOmega,identity, ...
    'VariableNames',{'speedRPM','normG','normKg','normKOmega', ...
    'stiffnessIdentityError'});
end

function tableValue=responseExtrema(modelData,responses,cfg)
nodes=double(cfg.action09.responseNodes(:));names=["stationary" "rotating"];
n=2*numel(nodes)*3;caseName=strings(n,1);speedRPM=zeros(n,1);
nodeId=zeros(n,1);component=strings(n,1);
displacementUnit=repmat("m",n,1);
accelerationUnit=repmat("m/s^2",n,1);
minimum=zeros(n,1);maximum=zeros(n,1);maximumAbsolute=zeros(n,1);
maximumAbsAcceleration=zeros(n,1);rowOut=0;labels=["ux" "uy" "uz"];
for caseIndex=1:2
    response=responses.(names(caseIndex));
    for nodeIndex=1:numel(nodes)
        modelRow=find(double(modelData.mesh.nodes.id)==nodes(nodeIndex),1);
        for componentIndexValue=1:3
            rowOut=rowOut+1;dof=modelData.dofs.node(modelRow,componentIndexValue);
            q=response.qFull(dof,:);a=response.absoluteAccelerationFull(dof,:);
            caseName(rowOut)=names(caseIndex);speedRPM(rowOut)=response.speedRPM;
            nodeId(rowOut)=nodes(nodeIndex);component(rowOut)=labels(componentIndexValue);
            minimum(rowOut)=min(q);maximum(rowOut)=max(q);
            maximumAbsolute(rowOut)=max(abs(q));maximumAbsAcceleration(rowOut)=max(abs(a));
        end
    end
end
tableValue=table(caseName,speedRPM,nodeId,component,displacementUnit, ...
    accelerationUnit,minimum,maximum,maximumAbsolute,maximumAbsAcceleration);
end

function tableValue=reactionSummary(modelData,response)
fixed=double(modelData.dofs.fixed(:));n=numel(fixed);nodeId=zeros(n,1);
component=strings(n,1);unit=strings(n,1);maximumAbsolute=zeros(n,1);
labels=["Fx" "Fy" "Fz" "Mx" "My" "Mz"];
for index=1:n
    [nodeRow,componentIndexValue]=find(modelData.dofs.node==fixed(index),1);
    nodeId(index)=double(modelData.mesh.nodes.id(nodeRow));
    component(index)=labels(componentIndexValue);
    if componentIndexValue<=3,unit(index)="N";else,unit(index)="N*m";end
    maximumAbsolute(index)=max(abs(response.constraintForcesFull(fixed(index),:)));
end
tableValue=table(nodeId,component,unit,maximumAbsolute);
end

function tableValue=elementSummary(elementForces)
elementId=elementForces.elementId;component=elementForces.component;
blade=elementForces.blade;
maximumAbsAxial=max(abs(elementForces.axialForce),[],2);
maximumAbsShear2=max(abs(elementForces.shearLocal2),[],2);
maximumAbsShear3=max(abs(elementForces.shearLocal3),[],2);
maximumAbsTorsion=max(abs(elementForces.torsionalMoment),[],2);
maximumAbsMoment2=max(abs(elementForces.bendingMomentLocal2),[],2);
maximumAbsMoment3=max(abs(elementForces.bendingMomentLocal3),[],2);
backwardError=elementForces.localGlobalBackwardError;
tableValue=table(elementId,component,blade,maximumAbsAxial, ...
    maximumAbsShear2,maximumAbsShear3,maximumAbsTorsion, ...
    maximumAbsMoment2,maximumAbsMoment3,backwardError);
end

function index=componentIndex(label)
switch lower(string(label))
    case {"ux","x","1"},index=1;
    case {"uy","y","2"},index=2;
    case {"uz","z","3"},index=3;
    case {"rx","4"},index=4;
    case {"ry","5"},index=5;
    case {"rz","6"},index=6;
    otherwise,error('validation:Action09:UnknownComponent', ...
            'Unknown component %s.',string(label));
end
end

function result=relative(errorValue,reference)
result=norm(errorValue,'fro')/max(norm(reference,'fro'),eps);
end

function item=makeCheck(name,pass,valueValue,tolerance,message,critical)
item=struct('name',string(name),'pass',logical(pass),'value',double(valueValue), ...
    'tolerance',double(tolerance),'message',string(message), ...
    'critical',logical(critical));
end

function result=value(source,path,defaultValue)
result=defaultValue;cursor=source;
for index=1:numel(path)
    if ~isstruct(cursor)||~isfield(cursor,path{index}),return,end
    cursor=cursor.(path{index});
end
if isnumeric(cursor)&&isscalar(cursor),result=double(cursor);
elseif islogical(cursor)&&isscalar(cursor),result=logical(cursor);
end
end
