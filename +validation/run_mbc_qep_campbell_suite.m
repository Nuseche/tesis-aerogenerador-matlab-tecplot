function suite=run_mbc_qep_campbell_suite( ...
        modelData,reduced,sweep,analysisModel,modalResults,cfg)
%RUN_MBC_QEP_CAMPBELL_SUITE Specialized Action-08 acceptance checks.

inverseTol=value(cfg,{'action08','inverseTolerance'},1e-12);
dotTol=value(cfg,{'action08','firstDerivativeTolerance'},1e-8);
ddotTol=value(cfg,{'action08','secondDerivativeTolerance'},2e-5);
homologyTol=value(cfg,{'action08','homologyTolerance'},1e-12);
zeroTol=value(cfg,{'action08','zeroSpeedFrequencyTolerance'},1e-6);
qepTol=value(cfg,{'action08','qepResidualTolerance'},1e-8);
pairTol=value(cfg,{'action08','pairTolerance'},1e-8);
leftTol=value(cfg,{'action08','leftResidualTolerance'},1e-8);
biorthTol=value(cfg,{'action08','biorthogonalityTolerance'},1e-6);
benchmarkTol=value(cfg,{'action08','benchmarkTolerance'},1e-10);
individualMinimum=value(cfg,{'action08','minimumIndividualTrackingMAC'},.8);
subspaceMinimum=value(cfg,{'action08','minimumSubspaceTrackingMAC'},.95);
effectiveMinimum=value(cfg,{'action08','minimumEffectiveTrackingMAC'},.8);
checks=repmat(check("",true,0,0,"",false),0,1);

[frameMetrics,transformTable,homologyTable]= ...
    frameAndDerivativeChecks(analysisModel,cfg);
checks(end+1,1)=check("mbc.frameOrthogonality", ...
    frameMetrics.maximumFrameIdentity<=inverseTol, ...
    frameMetrics.maximumFrameIdentity,inverseTol, ...
    "H is orthogonal at every sampled azimuth.",true);
checks(end+1,1)=check("mbc.combinedInverse", ...
    frameMetrics.maximumCombinedIdentity<=inverseTol, ...
    frameMetrics.maximumCombinedIdentity,inverseTol, ...
    "P inverse times P is identity at every sampled azimuth.",true);
checks(end+1,1)=check("mbc.firstDerivative", ...
    frameMetrics.firstDerivativeError<=dotTol, ...
    frameMetrics.firstDerivativeError,dotTol, ...
    "Analytic Pdot matches a centered finite difference.",true);
checks(end+1,1)=check("mbc.secondDerivative", ...
    frameMetrics.secondDerivativeError<=ddotTol, ...
    frameMetrics.secondDerivativeError,ddotTol, ...
    "Analytic Pddot matches a centered finite difference.",true);
checks(end+1,1)=check("mbc.inertialHomologousFrameDerivative", ...
    frameMetrics.frameDerivativeError<=dotTol,frameMetrics.frameDerivativeError,dotTol, ...
    "Time-dependent inertial Hdot agrees with independent finite differences.",true);
checks(end+1,1)=check("mbc.globalLocalReconstruction", ...
    frameMetrics.reconstructionError<=inverseTol, ...
    frameMetrics.reconstructionError,inverseTol, ...
    "Global/local reconstruction through P and Pinv.",true);
checks(end+1,1)=check("mbc.sixCollectiveMotions", ...
    frameMetrics.maximumCorrectCyclicRatio<=homologyTol, ...
    frameMetrics.maximumCorrectCyclicRatio,homologyTol, ...
    "Six identical local blade components become collective only.",true);
checks(end+1,1)=check("mbc.legacyGlobalMixingFailureExposed", ...
    frameMetrics.maximumLegacyCyclicRatio>0.1, ...
    frameMetrics.maximumLegacyCyclicRatio,0.1, ...
    "Direct mixing of global components is demonstrably nonhomologous.",true);

[zeroMetrics,zeroTable]=zeroSpeedEquivalence(sweep,modalResults,cfg);
checks(end+1,1)=check("mbc.zeroSpeedConservativeEquivalence", ...
    zeroMetrics.conservativeFrequencyError<=zeroTol, ...
    zeroMetrics.conservativeFrequencyError,zeroTol, ...
    "Untransformed and homologous-MBC conservative frequencies agree.",true);
checks(end+1,1)=check("qep.zeroSpeedNaturalFrequencyEquivalence", ...
    zeroMetrics.qepFrequencyError<=zeroTol,zeroMetrics.qepFrequencyError, ...
    zeroTol,"The zero-damping QEP recovers the conservative frequencies.",true);
checks(end+1,1)=check("mbc.zeroSpeedSubspaceEquivalence", ...
    zeroMetrics.subspaceMAC>=1-1e-8,zeroMetrics.subspaceMAC,1-1e-8, ...
    "Recovered MBC modes span the original zero-speed modal subspace.",true);

[qepMetrics,qepTable]=qepChecks(modalResults);
checks(end+1,1)=check("qep.allModesFinite",qepMetrics.allFinite, ...
    double(~qepMetrics.allFinite),0,"All requested eigenpairs are finite.",true);
checks(end+1,1)=check("qep.maximumRightResidual", ...
    qepMetrics.maximumResidual<=qepTol,qepMetrics.maximumResidual,qepTol, ...
    "Maximum normalized right QEP residual.",true);
checks(end+1,1)=check("qep.conjugatePairs", ...
    qepMetrics.maximumPairError<=pairTol,qepMetrics.maximumPairError,pairTol, ...
    "Maximum conjugate-pair consistency error.",true);
checks(end+1,1)=check("qep.leftModesAvailable",qepMetrics.leftAvailable, ...
    double(~qepMetrics.leftAvailable),0,"Left modes are stored at every speed.",true);
checks(end+1,1)=check("qep.maximumLeftResidual", ...
    qepMetrics.maximumLeftResidual<=leftTol,qepMetrics.maximumLeftResidual, ...
    leftTol,"Maximum normalized adjoint QEP residual.",true);
checks(end+1,1)=check("qep.biorthogonality", ...
    qepMetrics.maximumBiorthogonalityError<=biorthTol, ...
    qepMetrics.maximumBiorthogonalityError,biorthTol, ...
    "Off-diagonal QEP biorthogonality residual.",true);
checks(end+1,1)=check("qep.computedRootStability",qepMetrics.maximumRealPart<= ...
    1e-8*max(1,qepMetrics.maximumEigenvalueMagnitude), ...
    qepMetrics.maximumRealPart,1e-8*max(1,qepMetrics.maximumEigenvalueMagnitude), ...
    "No computed targeted root is unstable without nonconservative aerodynamic input.",true);

[benchmarkMetrics,assignmentTable]=solverAndTrackingBenchmarks();
checks(end+1,1)=check("benchmark.dampedSDOF", ...
    benchmarkMetrics.sdofError<=benchmarkTol,benchmarkMetrics.sdofError, ...
    benchmarkTol,"Damped SDOF QEP matches its analytical root and damping.",true);
checks(end+1,1)=check("benchmark.gyroscopicWhirl", ...
    benchmarkMetrics.whirlError<=benchmarkTol,benchmarkMetrics.whirlError, ...
    benchmarkTol,"Forward/backward whirl frequencies match closed form.",true);
checks(end+1,1)=check("tracking.globalAssignmentBeatsGreedy", ...
    benchmarkMetrics.optimalScore>benchmarkMetrics.greedyScore, ...
    benchmarkMetrics.optimalScore-benchmarkMetrics.greedyScore,0, ...
    "Global assignment resolves the known greedy counterexample.",true);
checks(end+1,1)=check("tracking.rotatedDegenerateSubspace", ...
    benchmarkMetrics.subspaceMAC>=1-1e-12,benchmarkMetrics.subspaceMAC, ...
    1-1e-12,"Subspace MAC is invariant to a rotated degenerate basis.",true);
checks(end+1,1)=check("tracking.individualDegenerateMACIsInsufficient", ...
    abs(benchmarkMetrics.individualMAC-.5)<=1e-12, ...
    benchmarkMetrics.individualMAC,.5, ...
    "The benchmark exposes why individual MAC alone is insufficient.",true);

[trackingMetrics,campbellTable,trackingTable]=trackingChecks(modalResults,cfg);
checks(end+1,1)=check("campbell.gridAndBranchCount", ...
    trackingMetrics.correctShape,double(~trackingMetrics.correctShape),0, ...
    "The canonical Campbell grid has nine speeds and twelve branches.",true);
checks(end+1,1)=check("campbell.finiteBranches",trackingMetrics.allFinite, ...
    double(~trackingMetrics.allFinite),0,"All Campbell values are finite.",true);
checks(end+1,1)=check("campbell.classificationPresent", ...
    trackingMetrics.classificationPresent, ...
    double(~trackingMetrics.classificationPresent),0, ...
    "Every stored branch has a nonempty physical classification.",true);
checks(end+1,1)=check("tracking.nonclusterIndividualMAC", ...
    trackingMetrics.minimumNonclusterIndividual>=individualMinimum, ...
    trackingMetrics.minimumNonclusterIndividual,individualMinimum, ...
    "Nonclustered branches meet the individual-MAC gate.",true);
checks(end+1,1)=check("tracking.lowIndividualJustifiedBySubspace", ...
    trackingMetrics.lowIndividualAllJustified, ...
    double(~trackingMetrics.lowIndividualAllJustified),0, ...
    "Every individual MAC below the gate belongs to a high-quality subspace.",true);
checks(end+1,1)=check("tracking.minimumSubspaceMAC", ...
    trackingMetrics.minimumSubspace>=subspaceMinimum, ...
    trackingMetrics.minimumSubspace,subspaceMinimum, ...
    "Minimum principal-angle MAC among tracked clusters.",true);
checks(end+1,1)=check("tracking.minimumEffectiveMAC", ...
    trackingMetrics.minimumEffective>=effectiveMinimum, ...
    trackingMetrics.minimumEffective,effectiveMinimum, ...
    "Minimum individual-or-subspace tracking quality.",true);

[storageMetrics,storageTable]=storedOperatorChecks(modalResults);
checks(end+1,1)=check("storage.transformsPersisted", ...
    storageMetrics.transformsPresent,double(~storageMetrics.transformsPresent),0, ...
    "Every solution stores H, P, Pinv, Pdot and Pddot.",true);
checks(end+1,1)=check("storage.operatorsSparseFinite", ...
    storageMetrics.operatorsSparseFinite, ...
    double(~storageMetrics.operatorsSparseFinite),0, ...
    "Every transformed M/D/K is sparse and finite.",true);

suite=struct('schemaVersion',"1.0.0", ...
    'scope',"homologous_frame_mbc_qep_and_optimal_campbell_tracking", ...
    'checks',checks,'checkTable',struct2table(checks), ...
    'campbellTable',campbellTable,'qepTable',qepTable, ...
    'trackingTable',trackingTable,'transformTable',transformTable, ...
    'homologyTable',homologyTable,'zeroSpeedTable',zeroTable, ...
    'assignmentTable',assignmentTable,'storageTable',storageTable, ...
    'metrics',struct('maximumCombinedIdentity', ...
    frameMetrics.maximumCombinedIdentity,'firstDerivativeError', ...
    frameMetrics.firstDerivativeError,'secondDerivativeError', ...
    frameMetrics.secondDerivativeError,'maximumCorrectCyclicRatio', ...
    frameMetrics.maximumCorrectCyclicRatio,'maximumLegacyCyclicRatio', ...
    frameMetrics.maximumLegacyCyclicRatio,'zeroSpeedFrequencyError', ...
    zeroMetrics.conservativeFrequencyError,'zeroSpeedQepError', ...
    zeroMetrics.qepFrequencyError,'maximumQepResidual',qepMetrics.maximumResidual, ...
    'maximumLeftResidual',qepMetrics.maximumLeftResidual, ...
    'maximumBiorthogonalityError',qepMetrics.maximumBiorthogonalityError, ...
    'minimumIndividualTrackingMAC',trackingMetrics.minimumIndividual, ...
    'minimumNonclusterIndividualMAC',trackingMetrics.minimumNonclusterIndividual, ...
    'minimumSubspaceTrackingMAC',trackingMetrics.minimumSubspace, ...
    'minimumEffectiveTrackingMAC',trackingMetrics.minimumEffective));
suite.passed=all([checks.pass]|~[checks.critical]);
suite.criticalFailures=checks(~[checks.pass]&[checks.critical]);
if logical(value(cfg,{'validation','failOnCritical'},1))&&~suite.passed
    names=strjoin(string({suite.criticalFailures.name}),', ');
    error('validation:run_mbc_qep_campbell_suite:CriticalFailure', ...
        'Action 08 critical checks failed: %s',names);
end
end

function [metrics,tableValue,homologyTable]=frameAndDerivativeChecks(model,cfg)
map=model.bladeDofMap;frameData=model.mbc.frameData;n=model.nDof;
azimuths=[-2*pi;-pi/3;0;.71;2*pi];omega=1.7;alpha=.2;
inverseError=zeros(numel(azimuths),1);frameError=inverseError;
for index=1:numel(azimuths)
    options=struct('nDof',n,'frameData',frameData,'angularAcceleration',alpha);
    d=rotor.mbc_derivatives(map,azimuths(index),omega,options);
    inverseError(index)=norm(d.Tinv*d.T-speye(n),'fro')/sqrt(n);
    frameError(index)=d.frame.identityError;
end
psi=.41;h=1e-5;options=struct('nDof',n,'frameData',frameData);
d=rotor.mbc_derivatives(map,psi,omega,options);
plus=rotor.mbc_derivatives(map,psi+omega*h,omega,options);
minus=rotor.mbc_derivatives(map,psi-omega*h,omega,options);
fdot=(plus.T-minus.T)/(2*h);fddot=(plus.T-2*d.T+minus.T)/(h^2);
dotError=norm(fdot-d.Tdot,'fro')/max(norm(d.Tdot,'fro'),1);
ddotError=norm(fddot-d.Tddot,'fro')/max(norm(d.Tddot,'fro'),1);
z=sin((1:n).'/19);reconstruction=norm(d.T*(d.Tinv*z)-z)/norm(z);
frameDerivativeNorm=norm(d.frame.Hdot,'fro')+norm(d.frame.Hddot,'fro');
frameDerivativeError=norm((plus.frame.H-minus.frame.H)/(2*h)- ...
    d.frame.Hdot,'fro')/max(norm(d.frame.Hdot,'fro'),1);

H=rotor.blade_frame_transformation(frameData,0,0,struct('nDof',n));
B=rotor.mbc_transformation(map,0,struct('nDof',n));station=18;
component=(1:6).';correct=zeros(6,1);legacy=zeros(6,1);
for localComponent=1:6
    row=(station-1)*6+localComponent;indices=map(row,:);
    qhom=zeros(n,1);qhom(indices)=1;qglobal=H.H*qhom;
    correctCoordinates=B.Tinv*(H.Hinv*qglobal);
    legacyCoordinates=B.Tinv*qglobal;
    correct(localComponent)=norm(correctCoordinates(indices(2:3)))/ ...
        max(abs(correctCoordinates(indices(1))),eps);
    legacy(localComponent)=norm(legacyCoordinates(indices(2:3)))/ ...
        max(abs(legacyCoordinates(indices(1))),eps);
end
homologyTable=table(component,correct,legacy, ...
    'VariableNames',{'component','correctCyclicRatio','legacyCyclicRatio'});
tableValue=table(azimuths,inverseError,frameError);
metrics=struct('maximumFrameIdentity',max(frameError), ...
    'maximumCombinedIdentity',max(inverseError), ...
    'firstDerivativeError',dotError,'secondDerivativeError',ddotError, ...
    'reconstructionError',reconstruction, ...
    'frameDerivativeNorm',frameDerivativeNorm, ...
    'frameDerivativeError',frameDerivativeError, ...
    'maximumCorrectCyclicRatio',max(correct), ...
    'maximumLegacyCyclicRatio',max(legacy));
end

function [metrics,tableValue]=zeroSpeedEquivalence(sweep,modalResults,cfg)
index=find(sweep.speedRPM==0,1);ops=sweep.ops{index}.reduced;
solution=modalResults.solutions{index};transformed=solution.transformedOperators;
nModes=size(modalResults.frequencyHz,2);options=cfg.modal;options.number=nModes;
original=modal.solve_conservative_modes(ops.M,ops.K,options);
mbc=modal.solve_conservative_modes(transformed.M,transformed.K,options);
zeroDampingQep=modal.solve_quadratic_modes(transformed.M, ...
    sparse(size(transformed.M,1),size(transformed.M,2)), ...
    transformed.K,options);
f0=sort(original.frequencyHz(:));fm=sort(mbc.frequencyHz(:));
fq=sort(zeroDampingQep.naturalFrequencyHz(:));
fqDamped=sort(solution.naturalFrequencyHz(:));
conservativeError=norm(fm-f0)/norm(f0);qepError=norm(fq-f0)/norm(f0);
dampedShift=norm(fqDamped-f0)/norm(f0);
recovered=solution.mbc.transformation.T*mbc.modes;
sub=modal.subspace_mac(original.modes,recovered,ops.M);
tableValue=table((1:nModes).',f0,fm,fq,fqDamped, ...
    'VariableNames',{'mode','originalHz','mbcHz','zeroDampingQepHz', ...
    'productionDampedQepNaturalHz'});
metrics=struct('conservativeFrequencyError',conservativeError, ...
    'qepFrequencyError',qepError,'productionDampedFrequencyShift', ...
    dampedShift,'subspaceMAC',sub.minimumMAC);
end

function [metrics,tableValue]=qepChecks(results)
nSpeed=numel(results.solutions);nModes=size(results.frequencyHz,2);n=nSpeed*nModes;
speedRPM=zeros(n,1);mode=speedRPM;realLambda=speedRPM;imagLambda=speedRPM;
residual=speedRPM;pairError=speedRPM;leftResidual=speedRPM;
spectrumComplete=false(n,1);
cursor=0;allFinite=true;leftAvailable=true;maxResidual=0;maxPair=0;
maxLeft=0;maxBiorth=0;maxReal=-inf;maxMagnitude=0;
for speed=1:nSpeed
    s=results.solutions{speed};count=numel(s.eigenvalues);
    leftAvailable=leftAvailable&&s.leftDiagnostics.available;
    maxResidual=max(maxResidual,max(s.residual));
    maxPair=max(maxPair,max(s.conjugatePairRelativeError,[],'omitnan'));
    if s.leftDiagnostics.available
        maxLeft=max(maxLeft,max(s.leftResidual));
        maxBiorth=max(maxBiorth,s.leftDiagnostics.maximumOffDiagonal);
    else,maxLeft=inf;maxBiorth=inf;end
    maxReal=max(maxReal,max(real(s.allEigenvalues)));
    maxMagnitude=max(maxMagnitude,max(abs(s.allEigenvalues)));
    allFinite=allFinite&&all(isfinite(s.eigenvalues))&& ...
        all(isfinite(s.modes),'all')&&all(isfinite(s.residual));
    for branch=1:count
        cursor=cursor+1;speedRPM(cursor)=results.speedRPM(speed);mode(cursor)=branch;
        realLambda(cursor)=real(s.eigenvalues(branch));
        imagLambda(cursor)=imag(s.eigenvalues(branch));residual(cursor)=s.residual(branch);
        pairError(cursor)=s.conjugatePairRelativeError(branch);
        spectrumComplete(cursor)=logical(s.spectrumComplete);
        if s.leftDiagnostics.available,leftResidual(cursor)=s.leftResidual(branch);
        else,leftResidual(cursor)=NaN;end
    end
end
tableValue=table(speedRPM(1:cursor),mode(1:cursor),realLambda(1:cursor), ...
    imagLambda(1:cursor),residual(1:cursor),pairError(1:cursor), ...
    leftResidual(1:cursor),spectrumComplete(1:cursor), ...
    'VariableNames',{'speedRPM','mode','realLambda', ...
    'imagLambda','residual','pairError','leftResidual','spectrumComplete'});
metrics=struct('allFinite',allFinite,'maximumResidual',maxResidual, ...
    'maximumPairError',maxPair,'leftAvailable',leftAvailable, ...
    'maximumLeftResidual',maxLeft,'maximumBiorthogonalityError',maxBiorth, ...
    'maximumRealPart',maxReal,'maximumEigenvalueMagnitude',maxMagnitude);
end

function [metrics,tableValue]=solverAndTrackingBenchmarks()
sdof=modal.solve_quadratic_modes(2,.4,8,struct('number',1));
expectedLambda=-.1+1i*sqrt(3.99);sdofError=max( ...
    abs(sdof.eigenvalues-expectedLambda)/abs(expectedLambda), ...
    abs(sdof.dampingRatio-.05));
m=3;k=120;gyro=1.8;omega=7;G=omega*[0 gyro;-gyro 0];
whirl=modal.solve_quadratic_modes(m*eye(2),G,k*eye(2),struct('number',2));
roots=[sqrt((gyro*omega)^2+4*m*k)-gyro*omega; ...
    sqrt((gyro*omega)^2+4*m*k)+gyro*omega]/(2*m)/(2*pi);
whirlError=norm(sort(whirl.dampedFrequencyHz)-sort(roots))/norm(roots);
score=[.9 .8;.85 .1];[assignment,optimalScore]=modal.optimal_assignment(score);
greedyScore=1.0;rotated=[1 1;-1 1]/sqrt(2);
sub=modal.subspace_mac(eye(2),rotated,eye(2));
individual=modal.modal_assurance_criterion(eye(2),rotated,eye(2));
tableValue=table([1;2],assignment(:), ...
    score(sub2ind(size(score),(1:2).',assignment(:))), ...
    'VariableNames',{'previousMode','assignedMode','assignedScore'});
metrics=struct('sdofError',sdofError,'whirlError',whirlError, ...
    'optimalScore',optimalScore,'greedyScore',greedyScore, ...
    'subspaceMAC',sub.minimumMAC,'individualMAC',individual(1,1));
end

function [metrics,campbellTable,trackingTable]=trackingChecks(results,cfg)
[nSpeed,nModes]=size(results.frequencyHz);n=nSpeed*nModes;
speedRPM=zeros(n,1);branch=speedRPM;frequencyHz=speedRPM;
naturalFrequencyHz=speedRPM;dampingRatio=speedRPM;classification=strings(n,1);
effectiveMAC=speedRPM;individualMAC=speedRPM;subspaceMAC=speedRPM;
frequencyChange=speedRPM;assignment=speedRPM;clusterId=speedRPM;
cursor=0;classificationPresent=true;
for speed=1:nSpeed
    labels=results.classification{speed}.labels;
    for mode=1:nModes
        cursor=cursor+1;speedRPM(cursor)=results.speedRPM(speed);branch(cursor)=mode;
        frequencyHz(cursor)=results.frequencyHz(speed,mode);
        naturalFrequencyHz(cursor)=results.naturalFrequencyHz(speed,mode);
        dampingRatio(cursor)=results.dampingRatio(speed,mode);
        classification(cursor)=labels(mode);classificationPresent= ...
            classificationPresent&&strlength(labels(mode))>0;
        effectiveMAC(cursor)=results.trackingMAC(speed,mode);
        individualMAC(cursor)=results.individualTrackingMAC(speed,mode);
        subspaceMAC(cursor)=results.subspaceTrackingMAC(speed,mode);
        frequencyChange(cursor)=results.trackingFrequencyChange(speed,mode);
        assignment(cursor)=results.trackingAssignment(speed,mode);
        clusterId(cursor)=results.trackingClusterId(speed,mode);
    end
end
campbellTable=table(speedRPM,branch,frequencyHz,naturalFrequencyHz, ...
    dampingRatio,classification);
trackingTable=table(speedRPM,branch,effectiveMAC,individualMAC, ...
    subspaceMAC,frequencyChange,assignment,clusterId);
sub=results.subspaceTrackingMAC(2:end,:);individual= ...
    results.individualTrackingMAC(2:end,:);effective=results.trackingMAC(2:end,:);
low=individual<value(cfg,{'action08','minimumIndividualTrackingMAC'},.8);
justified=~low|(~isnan(sub)&sub>= ...
    value(cfg,{'action08','minimumSubspaceTrackingMAC'},.95));
noncluster=individual(isnan(sub));
metrics=struct('correctShape',nSpeed==9&&nModes==12, ...
    'allFinite',all(isfinite(results.frequencyHz),'all')&& ...
    all(isfinite(results.naturalFrequencyHz),'all')&& ...
    all(isfinite(results.dampingRatio),'all'), ...
    'classificationPresent',classificationPresent, ...
    'minimumIndividual',min(individual,[],'all'), ...
    'minimumNonclusterIndividual',min(noncluster,[],'all'), ...
    'lowIndividualAllJustified',all(justified,'all'), ...
    'minimumSubspace',min(sub,[],'all','omitnan'), ...
    'minimumEffective',min(effective,[],'all'));
end

function [metrics,tableValue]=storedOperatorChecks(results)
n=numel(results.solutions);speedRPM=zeros(n,1);inverseError=speedRPM;
normM=speedRPM;normD=speedRPM;normK=speedRPM;
transforms=true;operators=true;
for index=1:n
    s=results.solutions{index};speedRPM(index)=results.speedRPM(index);
    transforms=transforms&&isfield(s,'mbc')&&isfield(s.mbc,'transformation')&& ...
        all(isfield(s.mbc.transformation,{'T','Tinv','Tdot','Tddot','frame'}));
    A={s.transformedOperators.M,s.transformedOperators.D,s.transformedOperators.K};
    operators=operators&&all(cellfun(@issparse,A))&& ...
        all(cellfun(@(X)all(isfinite(nonzeros(X))),A));
    inverseError(index)=s.mbc.transformation.identityError;
    normM(index)=norm(A{1},'fro');normD(index)=norm(A{2},'fro');normK(index)=norm(A{3},'fro');
end
tableValue=table(speedRPM,inverseError,normM,normD,normK);
metrics=struct('transformsPresent',transforms, ...
    'operatorsSparseFinite',operators);
end

function item=check(name,passValue,numericValue,tolerance,message,critical)
item=struct('name',string(name),'pass',logical(passValue), ...
    'value',double(numericValue),'tolerance',double(tolerance), ...
    'message',string(message),'critical',logical(critical));
end

function result=value(cfg,path,fallback)
result=fallback;cursor=cfg;
for index=1:numel(path)
    if ~isstruct(cursor)||~isfield(cursor,path{index}),return,end
    cursor=cursor.(path{index});
end
if (isnumeric(cursor)||islogical(cursor))&&isscalar(cursor)&&isfinite(cursor)
    result=double(cursor);
end
end
