function suite=run_mass_formulation_suite(modelData,Massembled,McDistributed, ...
    MhDistributed,Mc,Mh,Ke,Tc,reducedConsistent,reducedHrz, ...
    bodyReportConsistent,bodyReportHrz,propertiesConsistent,propertiesHrz, ...
    diagnosticsConsistent,diagnosticsHrz,cfg)
%RUN_MASS_FORMULATION_SUITE Acceptance checks for Action 05.

tol=localCfg(cfg,{'validation','massConservationTolerance'},1e-10);
symTol=localCfg(cfg,{'validation','matrixSymmetry'},1e-12);
checks=repmat(localCheck("",true,0,0,"",false),0,1);

checks(end+1,1)=localCheck("consistent.isDefault", ...
    lower(string(cfg.mass.formulation))=="consistent", ...
    double(lower(string(cfg.mass.formulation))~="consistent"),0, ...
    "The production case selects consistent mass.",true);
consistentDifference=norm(McDistributed-Massembled,'fro')/ ...
    max(norm(Massembled,'fro'),1);
checks(end+1,1)=localCheck("consistent.inputEqualsOutput", ...
    consistentDifference==0,consistentDifference,0, ...
    "Consistent formulation leaves assembled coefficients unchanged.",true);
checks(end+1,1)=localCheck("consistent.noAbsoluteMask", ...
    ~diagnosticsConsistent.usesAbsoluteValue, ...
    double(diagnosticsConsistent.usesAbsoluteValue),0, ...
    "No absolute value is used to hide mass signs.",true);

checks(end+1,1)=localCheck("hrz.explicitMethod", ...
    diagnosticsHrz.method=="hrz",double(diagnosticsHrz.method~="hrz"),0, ...
    "The optional diagonal method is explicitly HRZ.",true);
checks(end+1,1)=localCheck("hrz.distributedDiagonal",isdiag(MhDistributed), ...
    double(~isdiag(MhDistributed)),0, ...
    "Only the distributed HRZ matrix is diagonal.",true);
hrzDiagonal=full(diag(MhDistributed));
checks(end+1,1)=localCheck("hrz.nonnegativeDiagonal", ...
    all(hrzDiagonal>=0),min(hrzDiagonal),0, ...
    "HRZ never masks a negative diagonal.",true);
checks(end+1,1)=localCheck("hrz.translationMassConservation", ...
    diagnosticsHrz.translationMassRelativeError<=symTol, ...
    diagnosticsHrz.translationMassRelativeError,symTol, ...
    "Rigid translational mass is conserved in X, Y and Z.",true);
checks(end+1,1)=localCheck("hrz.noAbsoluteMask", ...
    ~diagnosticsHrz.usesAbsoluteValue,double(diagnosticsHrz.usesAbsoluteValue),0, ...
    "HRZ scaling does not alter signs through abs.",true);

[rowSumRejected,rowSumIdentifier]=localRowSumRejection(Massembled,cfg);
checks(end+1,1)=localCheck("rowSum.realModelRejected",rowSumRejected, ...
    double(~rowSumRejected),0, ...
    "Actual Timoshenko row-sum lumping must expose its negative diagonal ("+ ...
    rowSumIdentifier+").",true);

bodyBlockError=0;
for index=1:numel(bodyReportConsistent)
    A=bodyReportConsistent(index).spatialMassMatrix;
    B=bodyReportHrz(index).spatialMassMatrix;
    bodyBlockError=max(bodyBlockError,norm(A-B,'fro')/max(norm(A,'fro'),1));
end
checks(end+1,1)=localCheck("bodies.notDiagonalized",bodyBlockError==0, ...
    bodyBlockError,0,"Identical full 6x6 body blocks are added after either method.",true);
checks(end+1,1)=localCheck("hrz.totalMatrixRetainsBodyCoupling", ...
    ~isdiag(Mh),double(isdiag(Mh)),0, ...
    "The total HRZ comparison retains body tensor products/couplings.",true);

checks=[checks;localMatrixChecks(Mc,"consistent.full.M",symTol); ...
    localMatrixChecks(reducedConsistent.M,"consistent.reduced.M",symTol); ...
    localMatrixChecks(Mh,"hrz.full.M",symTol); ...
    localMatrixChecks(reducedHrz.M,"hrz.reduced.M",symTol); ...
    localMatrixChecks(Ke,"shared.full.Ke",symTol)]; %#ok<AGROW>
[~,pConsistent]=chol((reducedConsistent.M+reducedConsistent.M.')/2);
[~,pHrz]=chol((reducedHrz.M+reducedHrz.M.')/2);
checks(end+1,1)=localCheck("consistent.reducedPositiveDefinite", ...
    pConsistent==0,pConsistent,0,"Cholesky factorization of consistent Mr.",true);
checks(end+1,1)=localCheck("hrz.reducedPositiveDefinite", ...
    pHrz==0,pHrz,0,"Cholesky factorization of HRZ-comparison Mr.",true);

checks(end+1,1)=localCheck("consistent.constraintConservation", ...
    propertiesConsistent.constraintConservationError<=tol, ...
    propertiesConsistent.constraintConservationError,tol, ...
    "Production mass properties are conserved by Tc.",true);
totalMassDifference=abs(propertiesHrz.totalMassKg- ...
    propertiesConsistent.totalMassKg)/propertiesConsistent.totalMassKg;
checks(end+1,1)=localCheck("hrz.totalMass",totalMassDifference<=symTol, ...
    totalMassDifference,symTol, ...
    "HRZ and consistent alternatives have equal rigid-translation total mass.",true);
probe=sin((1:size(Tc,2)).'/23)+cos((1:size(Tc,2)).'/37);
consistentEnergyError=localRelative(probe.'*reducedConsistent.M*probe, ...
    (Tc*probe).'*Mc*(Tc*probe));
hrzEnergyError=localRelative(probe.'*reducedHrz.M*probe, ...
    (Tc*probe).'*Mh*(Tc*probe));
checks(end+1,1)=localCheck("consistent.congruenceEnergy", ...
    consistentEnergyError<=symTol,consistentEnergyError,symTol, ...
    "Consistent mass energy is preserved by Tc.",true);
checks(end+1,1)=localCheck("hrz.congruenceEnergy", ...
    hrzEnergyError<=symTol,hrzEnergyError,symTol, ...
    "HRZ-comparison mass energy is preserved by Tc.",true);

modalTable=localTowerModalComparison(modelData,cfg);
maxFrequencyDifference=max(abs(modalTable.frequencyRelativeDifference));
minimumMAC=min(modalTable.matchedMAC);
maximumResidual=max([modalTable.consistentResidual;modalTable.hrzResidual]);
freqTol=localCfg(cfg,{'action05','modalFrequencyDifferenceTolerance'},0.02);
macTol=localCfg(cfg,{'action05','modalMacTolerance'},0.9);
residualTol=localCfg(cfg,{'action05','modalResidualTolerance'},1e-8);
checks(end+1,1)=localCheck("comparison.frequencyDifference", ...
    maxFrequencyDifference<=freqTol,maxFrequencyDifference,freqTol, ...
    "Maximum relative tower-frequency change, consistent versus HRZ.",true);
checks(end+1,1)=localCheck("comparison.matchedMAC",minimumMAC>=macTol, ...
    minimumMAC,macTol, ...
    "Minimum best-match MAC, allowing exchange inside degenerate pairs.",true);
checks(end+1,1)=localCheck("comparison.modalResidual",maximumResidual<=residualTol, ...
    maximumResidual,residualTol,"Both modal solutions satisfy their eigenproblems.",true);
participationFinite=all(isfinite(modalTable{:, ...
    {'consistentParticipation','hrzParticipation'}}),'all');
checks(end+1,1)=localCheck("comparison.participationFinite", ...
    participationFinite,double(~participationFinite),0, ...
    "Translational effective-mass participation is exported for both methods.",true);

massComparisonTable=localMassComparison(propertiesConsistent,propertiesHrz, ...
    diagnosticsHrz);
diagnosticsTable=table(["consistent";"hrz"], ...
    [false;true],[false;false], ...
    [0;diagnosticsHrz.translationMassRelativeError], ...
    VariableNames={'method','distributedOutputDiagonal','usesAbsoluteValue', ...
    'translationMassRelativeError'});

suite=struct('schemaVersion',"1.0.0", ...
    'scope',"consistent_production_with_optional_hrz_sensitivity", ...
    'checks',checks,'checkTable',struct2table(checks), ...
    'massComparisonTable',massComparisonTable, ...
    'modalComparisonTable',modalTable,'diagnosticsTable',diagnosticsTable, ...
    'consistentProperties',propertiesConsistent,'hrzProperties',propertiesHrz, ...
    'metrics',struct('maxFrequencyRelativeDifference',maxFrequencyDifference, ...
    'minimumMatchedMAC',minimumMAC,'maximumModalResidual',maximumResidual, ...
    'hrzTranslationMassError',diagnosticsHrz.translationMassRelativeError, ...
    'totalMassDifference',totalMassDifference,'bodyBlockError',bodyBlockError));
suite.passed=all([checks.pass] | ~[checks.critical]);
suite.criticalFailures=checks(~[checks.pass] & [checks.critical]);
if logical(localCfg(cfg,{'validation','failOnCritical'},1))&&~suite.passed
    names=strjoin(string({suite.criticalFailures.name}),', ');
    error('validation:run_mass_formulation_suite:CriticalFailure', ...
        'Action 05 critical checks failed: %s',names);
end
end

function [passed,identifier]=localRowSumRejection(M,cfg)
rowCfg=cfg;rowCfg.mass.formulation="row_sum";
passed=false;identifier="no_error";
try
    assembly.apply_mass_formulation(M,rowCfg);
catch ME
    identifier=string(ME.identifier);
    passed=identifier=="assembly:apply_mass_formulation:NegativeRowSum";
end
end

function tableValue=localTowerModalComparison(modelData,cfg)
selector=modelData.mesh.elements.type=="tower";
subsystem=validation.extract_beam_subsystem(modelData,selector,1,"tower");
[Mc,K]=validation.assemble_beam_subsystem(subsystem,cfg);
[Mh,~]=assembly.hrz_lump_mass(Mc,subsystem.dofs);
number=localCfg(cfg,{'action05','numberComparisonModes'},8);
consistent=validation.solve_fixed_root_modes(Mc,K,subsystem.rootDofs,number);
hrz=validation.solve_fixed_root_modes(Mh,K,subsystem.rootDofs,number);
MAC=modal.modal_assurance_criterion(consistent.modes,hrz.modes,Mc);
[matchedMAC,matchedHrzMode]=max(MAC,[],2);
mode=(1:number).';
consistentFrequencyHz=consistent.frequencyHz;
hrzFrequencyHz=hrz.frequencyHz(matchedHrzMode);
frequencyRelativeDifference=(hrzFrequencyHz-consistentFrequencyHz)./ ...
    consistentFrequencyHz;
consistentResidual=consistent.residual;
hrzResidual=hrz.residual(matchedHrzMode);
consistentParticipation=localParticipation( ...
    consistent.modes,Mc,subsystem.dofs);
hrzParticipationAll=localParticipation(hrz.modes,Mh,subsystem.dofs);
hrzParticipation=hrzParticipationAll(matchedHrzMode);
tableValue=table(mode,consistentFrequencyHz,matchedHrzMode,hrzFrequencyHz, ...
    frequencyRelativeDifference,matchedMAC,consistentResidual,hrzResidual, ...
    consistentParticipation,hrzParticipation);
end

function participation=localParticipation(modes,M,dofMap)
number=size(modes,2);participation=zeros(number,1);
for direction=1:3
    influence=zeros(size(M,1),1);influence(dofMap(:,direction))=1;
    denominator=influence.'*M*influence;
    gamma=modes.'*M*influence;
    participation=participation+abs(gamma).^2/max(denominator,eps);
end
end

function tableValue=localMassComparison(consistent,hrz,diagnostics)
metric=["total_mass_kg";"cg_x_m";"cg_y_m";"cg_z_m"; ...
    "constraint_conservation_error";"translation_mass_error"];
consistentValue=[consistent.totalMassKg;consistent.centerOfMassGlobalM(:); ...
    consistent.constraintConservationError;0];
hrzValue=[hrz.totalMassKg;hrz.centerOfMassGlobalM(:); ...
    hrz.constraintConservationError;diagnostics.translationMassRelativeError];
relativeDifference=abs(hrzValue-consistentValue)./max(abs(consistentValue),1);
tableValue=table(metric,consistentValue,hrzValue,relativeDifference);
end

function checks=localMatrixChecks(A,label,tol)
checks=repmat(localCheck("",true,0,0,"",false),0,1);
checks(end+1,1)=localCheck(label+".sparse",issparse(A),double(~issparse(A)),0, ...
    "Matrix remains sparse.",true);
finite=all(isfinite(nonzeros(A)));
checks(end+1,1)=localCheck(label+".finite",finite,double(~finite),0, ...
    "Stored coefficients are finite.",true);
symmetry=norm(A-A.','fro')/max(norm(A,'fro'),eps);
checks(end+1,1)=localCheck(label+".symmetry",symmetry<=tol,symmetry,tol, ...
    "Relative Frobenius symmetry residual.",true);
end

function value=localRelative(a,b)
value=abs(a-b)/max([abs(a),abs(b),1]);
end

function check=localCheck(name,pass,value,tolerance,message,critical)
check=struct('name',string(name),'pass',logical(pass),'value',value, ...
    'tolerance',tolerance,'message',string(message),'critical',logical(critical));
end

function value=localCfg(cfg,path,fallback)
value=fallback;cursor=cfg;
for index=1:numel(path)
    if ~isstruct(cursor)||~isfield(cursor,path{index}),return;end
    cursor=cursor.(path{index});
end
if isnumeric(cursor)&&isscalar(cursor)&&isfinite(cursor),value=double(cursor);end
end
